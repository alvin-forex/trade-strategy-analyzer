PATTERNS = ["docs/*.html", "docs/**/*.html", "docs/*.md", "scripts/staticrypt/password_template_*.html"]


def main() -> int:
    files = set()
    for pat in PATTERNS:
        files.update(glob.glob(os.path.join(REPO_ROOT, pat)))
    if not files:
        print("language_check: no files matched — sparse checkout?")
        return 1
    bad = 0
    for path in sorted(files):
        rel = os.path.relpath(path, REPO_ROOT)
        try:
            with open(path, encoding="utf-8", errors="replace") as fh:
                text = fh.read()
        except OSError as exc:
            print(f"language_check: cannot read {rel}: {exc}")
            bad += 1
            continue
        for lineno, line in enumerate(text.split("\n"), 1):
            hits = [ch for ch in line if ch in SIMPLIFIED_ONLY]
            if hits:
                bad += 1
                idx = line.find(hits[0])
                ctx = line[max(0, idx - 20):idx + 25].strip()
                print(f"[簡體] {rel}:{lineno} {'|'.join(hits)} …{ctx}…")
    print(f"language_check: scanned {len(files)} files, violations {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
