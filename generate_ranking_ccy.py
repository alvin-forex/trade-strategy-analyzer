def get_score_class(score):
    if score >= 90: return 's90'
    elif score >= 80: return 's80'
    elif score >= 70: return 's70'
    elif score >= 60: return 's60'
    else: return 's0'

def get_dd_class(dd_value):
    """Pip-based DD thresholds: 500 / 2000 pips"""
    abs_dd = abs(dd_value)
    if abs_dd < 500:
        return 'dd-g'
    elif abs_dd < 2000:
        return 'dd-y'
    else:
        return 'dd-r'

def get_ea_style(ea_tag):
    parts = ea_tag.split('/')
    colors = {
        'DW': ('#1b5e20', '#a5d6a7'),
        'SMA': ('#0d47a1', '#90caf9'),
        'MKD': ('#4a148c', '#ce93d8'),
        'S10': ('#e65100', '#ffcc80'),
        'Flash': ('#b71c1c', '#ef9a9a'),
        'GEM': ('#004d40', '#80cbc4'),
        'UNK': ('#37474f', '#b0bec5'),
    }
    bg, fg = colors.get(parts[0], ('#37474f', '#b0bec5'))
    return f'background:{bg};color:{fg}'

def fmt_pips(val):
    """Format pip value without $ prefix"""
    if abs(val) >= 1000:
        return f'{val:,.0f}'
    elif abs(val) >= 100:
        return f'{val:.0f}'
    else:
        return f'{val:.1f}'

def fmt_pips_compact(val):
    """Compact pip display for table"""
    if val >= 10000:
        return f'{val/1000:.1f}k'
    return f'{val:,.0f}'


def generate_html(all_results):
    """Generate the full ranking_ccy.html from pip-based data."""

    # Separate scored vs red-card
    scored = [r for r in all_results if not r['red_card']]
    red = [r for r in all_results if r['red_card']]

