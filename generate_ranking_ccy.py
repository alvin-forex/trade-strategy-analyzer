def main():
    pkl_path = '/tmp/dde_v4_data.pkl'
    if not Path(pkl_path).exists():
        print("❌ Run dde_v4_scorer.py first to generate /tmp/dde_v4_data.pkl")
        sys.exit(1)

    with open(pkl_path, 'rb') as f:
        all_results = pickle.load(f)

    print(f"Loaded {len(all_results)} rows from pickle")

    html = generate_html(all_results)
    output_path = REPORTS_DIR / 'ranking_ccy.html'
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(html)

    print(f"✅ Generated: {output_path} ({len(html):,} bytes)")
    print(f"   Total rows: {len(all_results)}")


if __name__ == '__main__':
    main()
