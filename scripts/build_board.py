"""build_board.py — Taskboard v1 生成器（issue #17，TASKBOARD_SPEC v1）

資料源：GitHub Issues（lane:*/status:*/prio:* labels + assignee + milestone）
輸出：單一 HTML（內嵌 CSS/JS，零外部資源）
本卡規則：輸出首行帶 generated 標記；除時間戳外輸出完全可重現。

用法：
    GITHUB_TOKEN=xxx python scripts/build_board.py --out site/admin/tasks_board.html
    （--out 省略時寫到 stdout）
"""
import argparse
