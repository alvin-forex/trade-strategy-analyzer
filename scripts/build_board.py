import urllib.parse
import urllib.request

REPO = os.environ.get("GITHUB_REPOSITORY", "alvin-forex/trade-strategy-analyzer")
TOKEN = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN") or ""
API = "https://api.github.com"

STATUS_LABELS = ["backlog", "todo", "doing", "review", "blocked", "done"]
COLUMNS = {
    "backlog": "Backlog",
    "todo": "Todo",
    "doing": "In Progress",
    "review": "Review",
    "blocked": "Blocked",
    "done": "Done",
}
PRIO_ORDER = {"P0": 0, "P1": 1, "P2": 2}
GENERATED_MARK = "<!-- generated by scripts/build_board.py — do not edit by hand -->"


def api(url):
    req = urllib.request.Request(url)
    req.add_header("Accept", "application/vnd.github+json")
    req.add_header("User-Agent", "taskboard-builder")
    if TOKEN:
        req.add_header("Authorization", "Bearer %s" % TOKEN)
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def fetch_issues():
    issues, page = [], 1
    while True:
        q = urllib.parse.urlencode({"state": "all", "per_page": 100, "page": page})
        batch = api("%s/repos/%s/issues?%s" % (API, REPO, q))
        issues.extend(batch)
        if len(batch) < 100:
            break
        page += 1
    return [i for i in issues if "pull_request" not in i]


def fetch_comments(num):
    try:
        q = urllib.parse.urlencode({"per_page": 3, "sort": "created", "direction": "desc"})
        return api("%s/repos/%s/issues/%d/comments?%s" % (API, REPO, num, q))
    except Exception:
        return []


def esc(s):
    return (s or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def parse_deps(body):
    blocks, blocked = [], []
    for line in (body or "").splitlines():
        m = re.match(r"\s*(?:[-*]\s*)?Blocks:\s*(.+)$", line, re.I)
        if m:
            blocks += re.findall(r"#(\d+)", m.group(1))
        m = re.match(r"\s*(?:[-*]\s*)?Blocked by:\s*(.+)$", line, re.I)
        if m:
            blocked += re.findall(r"#(\d+)", m.group(1))
    return blocks, blocked


def parse_due(body, milestone):
    m = re.search(r"Due:\s*(\d{4}-\d{2}-\d{2})", body or "")
    if m:
        return m.group(1)
    if milestone and milestone.get("due_on"):
        return milestone["due_on"][:10]
    return ""


def build_cards(issues):
    cards, unlabelled = [], []
    for i in issues:
        labels = [l["name"] for l in i.get("labels", [])]
        status = next((s for s in STATUS_LABELS if ("status:%s" % s) in labels), None)
        prio_l = next((l for l in labels if l.startswith("prio:")), None)
        prio = prio_l.split(":", 1)[1] if prio_l else "P2"
        lane_l = next((l for l in labels if l.startswith("lane:")), None)
        lane = lane_l.split(":", 1)[1] if lane_l else ""
        assignee = i.get("assignee")
        owner = assignee["login"] if assignee else "未指派"
        due = parse_due(i.get("body"), i.get("milestone"))
        blocks, blocked_by = parse_deps(i.get("body"))
        comments = fetch_comments(i["number"]) if i.get("comments") else []
        activity = [
            {
                "user": c["user"]["login"],
                "at": c["created_at"][:16].replace("T", " "),
                "text": (c.get("body") or "")[:60],
            }
            for c in comments
        ]
        card = {
            "num": i["number"],
            "title": i["title"],
            "lane": lane,
            "owner": owner,
            "prio": prio,
            "status": status,
            "due": due,
            "blocks": blocks,
            "blocked_by": blocked_by,
            "activity": activity,
            "labels": labels,
        }
        if status is None:
            unlabelled.append(card)
        cards.append(card)
    for c in cards:
        if c["status"] is None:
            c["status"] = "backlog"
    return cards, unlabelled


def sort_key(c):
    return (PRIO_ORDER.get(c["prio"], 2), c["due"] or "9999-12-31", c["num"])


def deps_html(card, kind):
    ids = card["blocks"] if kind == "blocks" else card["blocked_by"]
    if not ids:
        return ""
    links = ", ".join(
        '<a href="https://github.com/%s/issues/%s" target="_blank" rel="noopener">#%s</a>'
        % (REPO, n, n)
        for n in ids
    )
    label = "Blocks" if kind == "blocks" else "Blocked by"
    return '<div class="dep">%s: %s</div>' % (label, links)


def activity_html(card):
    if not card["activity"]:
        return ""
    rows = "".join(
        "<li>%s — %s — %s</li>" % (esc(a["at"]), esc(a["user"]), esc(a["text"]))
        for a in card["activity"]
    )
    return '<details class="activity"><summary>Activity</summary><ul>%s</ul></details>' % rows


def card_html(c):
    cls = "card prio-%s" % c["prio"].lower()
    return (
        '<div class="%s" draggable="true" data-num="%d" data-lane="%s" data-owner="%s" '
        'data-prio="%s" data-title="%s">'
        '<div class="ctitle">%s</div>'
        '<div class="cfoot">%s｜%s｜<a href="https://github.com/%s/issues/%d" target="_blank" rel="noopener">#%d</a>｜%s</div>'
        "%s%s</div>"
    ) % (
        esc(cls),
        c["num"],
        esc(c["lane"]),
        esc(c["owner"]),
        esc(c["prio"]),
        esc(c["title"]),
        esc(c["title"]),
        esc(c["lane"]),
        esc(c["owner"]),
        REPO,
        c["num"],
        c["num"],
        esc(c["due"] or "—"),
        deps_html(c, "blocks"),
        deps_html(c, "blocked_by"),
    ) + activity_html(c)


