#!/usr/bin/env python3
"""w5_survey_20261105.py — W5 前置勘察：P2 532 頁結構普查（0700 總派工單 W5）

範圍：docs/reports（475）＋docs/ccy（36）＋docs/ccy_power（4）＋docs/portfolios（11）＋docs/admin（6）
每人一頁掃描：
  - NAV 四件（sidebar.css/tsa_tokens.css/sidebar-container/sidebar.js）
  - 加密殼（staticrypt）
  - 生成器簽名（Generated by …）
  - 色域普查：舊畫布 #0a0e17/#0d1117、金 #FFD700（標題域）、紫系裝飾、legacy hex
  - <style>/<script>/<table> 計數（結構指紋，同構分族用）
輸出：族清單＋統計＋建議施工分類（頁面層可做 vs 生成器層 vs 加密層）
"""
import re
import sys
from pathlib import Path
from collections import Counter, defaultdict

BASE = Path('/home/z/my-project/exchange-repo')
DOCS = BASE / 'docs'

SCOPES = {
    'reports': DOCS / 'reports',
    'ccy': DOCS / 'ccy',
    'ccy_power': DOCS / 'ccy_power',
    'portfolios': DOCS / 'portfolios',
    'admin': DOCS / 'admin',
}

# 色域掃描鍵（legacy 畫布/金標題/紫裝飾）
CANVAS_OLD = ('0a0e17', '0d1117', '0f0f23', '1a1a2e', '0a0a1a', '0a0a18')
GOLD = 'ffd700'
PURPLE_DECOR = ('2d1b69', '1a1a3e', '1a1f3a', '2d1b4e', '667eea', '764ba2', '9b59b6')
CANON = ('0f1520', '5ca8ff', 'a8b4c4')


def head_of(html: str) -> str:
    return html[:4096].lower()


def survey_page(p: Path) -> dict:
    html = p.read_text(encoding='utf-8', errors='replace')
    low = html.lower()
    head = head_of(html)
    sig = ''
    m = re.search(r'generated by [^<\n"]{2,60}', low)
    if m:
        sig = m.group(0)[:60]
    return {
        'file': p,
        'size': len(html),
        'encrypted': 'staticrypt' in head,
        'sidebar_css': 'sidebar.css' in html,
        'tokens': 'tsa_tokens.css' in html,
        'container': 'sidebar-container' in html,
        'sidebar_js': 'src="sidebar.js"' in html or "src='./sidebar.js'" in html or re.search(r'src="[^"]*sidebar\.js"', html) is not None,
        'nav_c': 'class="nav"' in html or 'navdrawer' in html,
        'gen': sig,
        'n_style': low.count('<style'),
        'n_script': low.count('<script'),
        'n_table': low.count('<table'),
        'canvas_old': sum(low.count('#' + c) for c in CANVAS_OLD),
        'gold': low.count('#' + GOLD) + low.count('255,215,0'),
        'purple': sum(low.count('#' + c) for c in PURPLE_DECOR),
        'canon': sum(low.count('#' + c) for c in CANON),
        'h1gold': bool(re.search(r'h1\s*\{[^}]*#?ffd700', low)),
    }


def main():
    rows = []
    for name, d in SCOPES.items():
        if not d.exists():
            print(f'[WARN] {name}: 目錄不存在')
            continue
        files = sorted(d.glob('*.html'))
        print(f'== {name}: {len(files)} 頁 ==')
        for p in files:
            try:
                rows.append((name, survey_page(p)))
            except Exception as e:
                print(f'  [ERR] {p.name}: {e}')

    print(f'\n===== 總計 {len(rows)} 頁 =====')

    # 1) 四件齊全率
    full = [r for _, r in rows if r['sidebar_css'] and r['tokens'] and r['container'] and r['sidebar_js']]
    print(f'NAV 四件齊: {len(full)}/{len(rows)}')

    # 2) 缺件分佈
    miss = Counter()
    for _, r in rows:
        if not (r['sidebar_css'] and r['tokens'] and r['container'] and r['sidebar_js']):
            parts = []
            if not r['sidebar_css']: parts.append('css')
            if not r['tokens']: parts.append('token')
            if not r['container']: parts.append('cont')
            if not r['sidebar_js']: parts.append('js')
            miss['+'.join(parts)] += 1
    print('缺件分佈:', dict(miss.most_common(8)))

    # 3) 加密頁
    enc = [(s, r) for s, r in rows if r['encrypted']]
    print(f'加密頁: {len(enc)} →', [f"{s}/{r['file'].name}" for s, r in enc][:10])

    # 4) 生成器簽名族
    gens = Counter(r['gen'] for _, r in rows if r['gen'])
    print('生成器簽名族:', dict(gens.most_common(12)))

    # 5) 色域
    old_canvas = [(s, r) for s, r in rows if r['canvas_old'] > 0]
    purple = [(s, r) for s, r in rows if r['purple'] > 0]
    h1gold = [(s, r) for s, r in rows if r['h1gold']]
    print(f'舊畫布色頁: {len(old_canvas)} | 紫裝飾頁: {len(purple)} | h1 金標題頁: {len(h1gold)}')

    # 6) 按目錄彙總
    print('\n===== 分目錄彙總 =====')
    for name in SCOPES:
        sub = [(s, r) for s, r in rows if s == name]
        if not sub:
            continue
        four = sum(1 for _, r in sub if r['sidebar_css'] and r['tokens'] and r['container'] and r['sidebar_js'])
        oldc = sum(1 for _, r in sub if r['canvas_old'] > 0)
        pur = sum(1 for _, r in sub if r['purple'] > 0)
        gld = sum(1 for _, r in sub if r['gold'] > 0)
        encc = sum(1 for _, r in sub if r['encrypted'])
        print(f'{name:10s} {len(sub):4d}頁 | 四件齊 {four:4d} | 舊畫布 {oldc:4d} | 紫 {pur:3d} | 金 {gld:3d} | 密 {encc}')

    # 7) 同構分族（結構指紋：style/script/table 計數 + 缺件模式 + gen 簽名）
    fam = defaultdict(list)
    for s, r in rows:
        key = (r['gen'], r['n_style'], r['n_script'], r['n_table'],
               r['sidebar_css'], r['tokens'], r['container'], r['sidebar_js'], r['encrypted'])
        fam[key].append(f"{s}/{r['file'].name}")
    print(f'\n===== 同構族（指紋=gen簽名+結構計數+四件）: {len(fam)} 族 =====')
    for key, members in sorted(fam.items(), key=lambda kv: -len(kv[1]))[:15]:
        print(f'{len(members):4d}頁 gen={key[0][:40]!r} style={key[1]} script={key[2]} table={key[3]} 四件={key[4:8]} 密={key[8]}')
        print(f'      樣本: {members[0]}')

    # 8) 建議分類輸出
    print('\n===== 施工分類建議 =====')
    page_layer = [(s, r) for s, r in rows if not r['encrypted'] and not r['gen']]
    gen_layer = [(s, r) for s, r in rows if not r['encrypted'] and r['gen']]
    print(f'A 頁面層可做（明文+無生成器簽名）: {len(page_layer)}')
    print(f'B 帶生成器簽名（重生成族，查明生成器）: {len(gen_layer)} → 簽名族:')
    for g, n in Counter(r['gen'] for _, r in gen_layer).most_common(10):
        print(f'   {n:4d}頁  {g[:60]}')

    # 匯出 JSON 供後續施工用
    import json
    out = BASE / 'scripts' / 'w5_survey_result_20261105.json'
    data = []
    for s, r in rows:
        data.append({'scope': s, 'name': r['file'].name, 'size': r['size'],
                     'encrypted': r['encrypted'], 'nav4': [r['sidebar_css'], r['tokens'], r['container'], r['sidebar_js']],
                     'nav_c': r['nav_c'], 'gen': r['gen'],
                     'style': r['n_style'], 'script': r['n_script'], 'table': r['n_table'],
                     'canvas_old': r['canvas_old'], 'gold': r['gold'], 'purple': r['purple'], 'canon': r['canon']})
    out.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding='utf-8')
    print(f'\n明細 JSON → {out}')


if __name__ == '__main__':
    sys.exit(main())
