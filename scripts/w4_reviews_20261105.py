#!/usr/bin/env python3
"""w4_reviews_20261105.py — W4（reviews 8 頁）：NAV 四件注入＋canvas remap（0700 總派工單 W4）

背景：docs/reviews/ 8 頁（index.html 1＋monthly/ 2＋weekly/ 5；頁尾簽名
「Generated by TSA | 2026-06-21」，生成器已不存在＝歷史靜態頁無重生成風險，
0846 信授權頁面層直做）。全裸零 sidebar 引用。

普查結論（8/8）：
  - index.html（42KB，depth-1）：GitHub-dark var 驅動（var()×100），[data-theme] 雙塊；
    tokens css 注入後同名 var（--bg/--bg-card/--bg-hover/--text/--text2）由正本接管自動
    canonical；僅 --bg-input:#0d1117 等 tokens 未定義名要 remap（全域 CI 一併清）。
  - 報告 7 頁（depth-2，hardcode var=0）：GitHub-dark 畫布 #0d1117×3（body/html 等）；
    熱力紫 ramp #4a148c/#ce93d8、警示橙 #e65100/#ffcc80、熱力綠 #1b5e20/#a5d6a7、
    GitHub 語義 #3fb950/#f85149/#58a6ff/#21262d/#8b949e/#c9d1d9 全屬語義/熱力域保留（2b）。
做法：NAV 四件（深度感知 prefix：index=../、monthly|weekly=../../）＋canvas remap
#0d1117→#0F1520（全域 CI 等長，照 W1 畫布規則）；語義色零觸碰。
附帶：docs/sidebar.js depth 邏輯通用化（rootSub 白名單→路徑段數推深度），
對現有 0/1 層頁逐頁等價，二層頁（reviews/monthly|weekly）由死鏈變可用——另行 commit 申報。
用法：python3 w4_reviews_20261105.py [--dry|--verify]
"""
import re
import sys
from pathlib import Path

BASE = Path('/home/z/my-project/exchange-repo')
REV = BASE / 'docs/reviews'
PAGES = sorted(REV.glob('*.html')) + sorted((REV / 'monthly').glob('*.html')) + \
        sorted((REV / 'weekly').glob('*.html'))
# 8 頁＝1＋2＋5（.json 唔入冊）


def prefix_for(p: Path) -> str:
    return '../' if p.parent == REV else '../../'


def head_inj(pre: str) -> str:
    return ('<!-- W4（2026-11-05）：NAV 四件 1+2——sidebar.css＋tsa_tokens.css -->\n'
            f'<link rel="stylesheet" href="{pre}sidebar.css">\n'
            f'<link rel="stylesheet" href="{pre}tsa_tokens.css">\n')


BODY_INJ = ('<!-- W4：NAV 之 #sidebar-container -->\n<div id="sidebar-container"></div>\n')
TAIL_T = '<script src="{pre}sidebar.js"></script>\n'


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else 'run'
    dry, verify = mode == '--dry', mode == '--verify'
    done = skip = fail = 0
    fails = []
    remap_tot = 0
    for p in PAGES:
        t = p.read_text(encoding='utf-8', errors='replace')
        if 'sidebar-container' in t or 'sidebar.js' in t:
            skip += 1
            continue
        pre = prefix_for(p)
        t, k = re.subn('#0d1117', '#0F1520', t, flags=re.IGNORECASE)
        remap_tot += k
        if t.count('</head>') != 1:
            fail += 1; fails.append(f'{p}: </head> ×{t.count("</head>")}'); continue
        mb = re.findall(r'<body[^>]*>', t)
        if len(mb) != 1:
            fail += 1; fails.append(f'{p}: <body> ×{len(mb)}'); continue
        if t.count('</body>') != 1:
            fail += 1; fails.append(f'{p}: </body> ×{t.count("</body>")}'); continue
        hinj = head_inj(pre)
        tinj = TAIL_T.format(pre=pre)
        t2 = t.replace('</head>', hinj + '</head>')
        t2 = re.sub(r'(<body[^>]*>)', r'\1' + BODY_INJ, t2, count=1)
        i = t2.find('</body>')
        t2 = t2[:i] + tinj + t2[i:]
        strip = lambda s: s.replace(hinj, '').replace(BODY_INJ, '').replace(tinj, '')
        if strip(t2) != t:
            fail += 1; fails.append(f'{p}: 插入後原文不對齊'); continue
        if not dry and not verify:
            p.write_text(t2, encoding='utf-8')
        done += 1
        if done <= 3 or dry:
            print(f'  [{"DRY" if dry else "OK"}] {p.relative_to(BASE)} pre={pre} remap×{k}')
    print(f'\n=== {mode or "run"}：改{done} 跳{skip} 敗{fail}（共{len(PAGES)}） canvas remap 總計 {remap_tot} ===')
    for f in fails[:10]:
        print('  FAIL:', f)

    if verify:
        bad = 0
        for p in PAGES:
            t = p.read_text(encoding='utf-8', errors='replace')
            pre = prefix_for(p)
            css = t.count(f'<link rel="stylesheet" href="{pre}sidebar.css">')
            tok = t.count(f'<link rel="stylesheet" href="{pre}tsa_tokens.css">')
            js = t.count(f'<script src="{pre}sidebar.js"></script>')
            cont = t.count('<div id="sidebar-container"></div>')
            legacy = t.lower().count('#0d1117')
            if not (css == 1 and tok == 1 and js == 1 and cont == 1 and legacy == 0):
                bad += 1
                print(f'  [VERIFY-FAIL] {p.relative_to(BASE)} css={css} tok={tok} js={js} cont={cont} legacy={legacy}')
        print(f'=== verify：{"PASS 8/8" if bad == 0 and len(PAGES) == 8 else f"FAIL {bad}"} ===')
        return 0 if bad == 0 and len(PAGES) == 8 else 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
