#!/usr/bin/env python3
"""w5c_signal_deep_20261105.py — W5-C（Signal_Deep 81 頁）：NAV 注入＋殼 remap（0700 總派工單 W5）

背景：docs/reports/Signal_Deep_Analysis_*.html 81 頁（57 頁「Generated by Trade Strategy
Analyzer v3」＋24 頁「Generated by TSA v3.9」；batch_generate_deep_reports.py 產物，
頁面最後 commit 2026-10-27 三週靜態＝頁層批次安全）全裸零 sidebar 引用。

普查結論（2026-11-05，81/81 覆蓋）：
  - v3（57 頁）＝暗畫布族：body/.container bg #0d1117×2／h1-h2 #1976d2（24-62/頁）／
    .subtitle #666／淺色語義塊（#e8f5e9/#e8eaf6/#fff8e1…）——同 W1 detailed 族完全同款。
  - v3.9（24 頁）＝light var 驅動族：:root --bg:#f5f7fa/--primary:#0f3460 navy／
    Bootstrap 語義色（#28a745/#dc3545/#ffc107）。

做法（頁層批次，錨點 81/81 全一普查實證——</head>×1／<body…>×1／</body>×1）：
  - v3：殼 remap 三條（照抄 W1 p1a_detailed_batch_20261105.py）＋四件注入——
    ① #0d1117→#0F1520（暗畫布，全域 CI 等長）② #1976d2→#5CA8FF（標題，全域 CI）
    ③ .subtitle{…color:#666}→#A8B4C4（regex 限定；淺卡內 #666 唔掂）
    ＋../sidebar.css＋../tsa_tokens.css（head 尾；殼值已＝canonical，tokens inert）
    ＋#sidebar-container（body 頂）＋../sidebar.js（body 尾）。
  - v3.9：三件注入——豁免 tsa_tokens.css：tokens :root dark 值喺全站 dark default
    （sidebar.js line 33 強制 data-theme=localStorage['tsa-theme']||'dark'）下會接管
    var(--bg/--text/--primary) 令頁面翻黑破版（硬編碼 #fff×267/#333 卡字留 light 態→
    混合破版）；同 tug_of_war_calculator.html light 規範族先例（有 sidebar 無 tokens，
    第一波已收貨）。內容／變量零改動，dark/light 兩 toggle 態均穩定。
語義色：Material（#2e7d32/#c62828/#e8f5e9…）／Bootstrap（#28a745/#dc3545…）狀態色、
淺語義塊、紫漸變 #667eea→#764ba2（W1 同款本波保留）、gold 數據位全不動。
用法：python3 w5c_signal_deep_20261105.py [--dry|--verify]
"""
import re
import sys
from pathlib import Path

BASE = Path('/home/z/my-project/exchange-repo')
PAGES = sorted((BASE / 'docs/reports').glob('Signal_Deep_Analysis_*.html'))

HEAD_V3 = ('<!-- W5-C（2026-11-05）：NAV 四件 1+2——sidebar.css＋tsa_tokens.css'
           '（殼已 remap canonical，tokens inert） -->\n'
           '<link rel="stylesheet" href="../sidebar.css">\n'
           '<link rel="stylesheet" href="../tsa_tokens.css">\n')
HEAD_V39 = ('<!-- W5-C（2026-11-05）：NAV 三件 1+2——sidebar.css；tokens 豁免'
            '（var 驅動 light 設計＋全站 dark default 會翻黑，同 tug light 規範族先例） -->\n'
            '<link rel="stylesheet" href="../sidebar.css">\n')
BODY_INJ = ('<!-- W5-C：NAV 之 #sidebar-container -->\n<div id="sidebar-container"></div>\n')
TAIL_INJ = '<script src="../sidebar.js"></script>\n'

# --- 殼 remap（照抄 W1：case-insensitive，等長） ---
HEX_CI = {
    '0d1117': '0F1520',   # 暗畫布 body/.container
    '1976d2': '5CA8FF',   # h1/h2 標題
}
# 暗畫布 subtitle 次要文字（.subtitle rule 內 #666；淺卡內 #666 唔掂）
SUBTITLE_RE = (re.compile(r'(\.subtitle\s*\{[^}]*?color:\s*)#666(?=[;,}])'),
               r'\1#A8B4C4')
LEGACY_KEYS = ['0d1117', '1976d2']   # v3 驗收殘留＝0


def classify(t: str) -> str:
    low = t.lower()
    if 'generated by tsa v3.9' in low:
        return 'v39'
    if 'generated by trade strategy analyzer v3' in low:
        return 'v3'
    return '?'
    # '?'＝未知簽名，一律 fail-close 唔動


def apply_remaps(html):
    n = {}
    for old, new in HEX_CI.items():
        html, k = re.subn('#' + old, '#' + new, html, flags=re.IGNORECASE)
        n[old] = k
    pat, repl = SUBTITLE_RE
    html, k = pat.subn(repl, html)
    n['subtitle666'] = k
    return html, n


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else 'run'
    dry, verify = mode == '--dry', mode == '--verify'
    done = skip = fail = 0
    fails = []
    fmts = {'v3': 0, 'v39': 0, '?': 0}
    remap_tot = {'0d1117': 0, '1976d2': 0, 'subtitle666': 0}
    for p in PAGES:
        t = p.read_text(encoding='utf-8', errors='replace')
        fmt = classify(t)
        fmts[fmt] += 1
        if fmt == '?':
            fail += 1; fails.append(f'{p.name}: 生成器簽名不明'); continue
        already_nav = 'sidebar-container' in t or 'sidebar.js' in t
        if already_nav:
            skip += 1  # 已注入（冪等閘）
            continue
        # --- v3 殼 remap（注入前） ---
        remap_n = None
        if fmt == 'v3':
            t, remap_n = apply_remaps(t)
            for k, v in remap_n.items():
                remap_tot[k] += v
        # --- 三錨點（全一先至動） ---
        if t.count('</head>') != 1:
            fail += 1; fails.append(f'{p.name}: </head> ×{t.count("</head>")}'); continue
        mb = re.findall(r'<body[^>]*>', t)
        if len(mb) != 1:
            fail += 1; fails.append(f'{p.name}: <body> ×{len(mb)}'); continue
        if t.count('</body>') != 1:
            fail += 1; fails.append(f'{p.name}: </body> ×{t.count("</body>")}'); continue
        head_inj = HEAD_V3 if fmt == 'v3' else HEAD_V39
        t2 = t.replace('</head>', head_inj + '</head>')
        t2 = re.sub(r'(<body[^>]*>)', r'\1' + BODY_INJ, t2, count=1)
        i = t2.find('</body>')
        t2 = t2[:i] + TAIL_INJ + t2[i:]
        # --- 純插入自證：除注入位外零改動（remap 後對齊） ---
        strip = lambda s: s.replace(head_inj, '').replace(BODY_INJ, '').replace(TAIL_INJ, '')
        if strip(t2) != t:
            fail += 1; fails.append(f'{p.name}: 插入後原文不對齊（唔應該發生）'); continue
        log = []
        if remap_n:
            log.append('remap:' + ','.join(f'{k}×{v}' for k, v in remap_n.items() if v))
        log.append(f'{fmt}:nav')
        if not dry and not verify:
            p.write_text(t2, encoding='utf-8')
        done += 1
        if done <= 3 or dry:
            print(f'  [{"DRY" if dry else "OK"}] {p.name} {log}')
    print(f'\n=== {mode or "run"}：改{done} 跳{skip} 敗{fail}（共{len(PAGES)}；族計 {fmts}） ===')
    if fmts['v3']:
        print(f'  remap 總計: {remap_tot}')
    for f in fails[:10]:
        print('  FAIL:', f)

    if verify:
        bad = 0
        for p in PAGES:
            t = p.read_text(encoding='utf-8', errors='replace')
            fmt = classify(t)
            css = t.count('<link rel="stylesheet" href="../sidebar.css">')
            js = t.count('<script src="../sidebar.js"></script>')
            cont = t.count('<div id="sidebar-container"></div>')
            tok = t.count('<link rel="stylesheet" href="../tsa_tokens.css">')
            if fmt == 'v3':
                legacy = sum(t.lower().count('#' + k) for k in LEGACY_KEYS)
                ok = css == 1 and js == 1 and cont >= 1 and tok == 1 and legacy == 0
                if ok:
                    m = re.search(r'\.subtitle\s*\{[^}]*?color:\s*#A8B4C4', t)
                    ok = m is not None
                    if not ok:
                        print(f'  [VERIFY-FAIL] {p.name} fmt=v3 subtitle 未轉 #A8B4C4')
                        bad += 1
                        continue
            elif fmt == 'v39':
                # 三件＋tokens 必須豁免（0 處）＋頁自身 :root navy 完好（設計零改動證據）
                ok = css == 1 and js == 1 and cont >= 1 and tok == 0 and '#0f3460' in t
            else:
                ok = False
            if not ok and fmt != 'v3':
                bad += 1
                print(f'  [VERIFY-FAIL] {p.name} fmt={fmt} css={css} js={js} cont={cont} tok={tok}')
            elif not ok and fmt == 'v3':
                bad += 1
                legacy = sum(t.lower().count('#' + k) for k in LEGACY_KEYS)
                print(f'  [VERIFY-FAIL] {p.name} fmt=v3 css={css} js={js} cont={cont} tok={tok} legacy={legacy}')
        print(f'=== verify：{"PASS 81/81" if bad == 0 and len(PAGES) == 81 else f"FAIL {bad}"} ===')
        return 0 if bad == 0 and len(PAGES) == 81 else 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
